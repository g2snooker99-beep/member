"use strict";
// Shared by emulator CI and the isolated real Firestore staging rehearsal.
const assert=require("node:assert/strict"),{createHash,randomBytes}=require("node:crypto");
const {buildService}=require("./service"),safety=require("./data-safety");
async function releaseScenarios({db,root,FieldValue,FieldPath,Timestamp,GeoPoint,runId,physicalDb}){
  const prefix=createHash("sha256").update(runId).digest("hex").slice(0,28);
  const checks=[],uid=n=>"U"+prefix+n.toString(16).padStart(4,"0"),A=uid(1),S=uid(2),ids=[10,11,12,13,14,15].map(uid);
  let clock=new Date("2026-10-21T12:00:00Z");
  const service=buildService({db,auth:{},FieldValue,FieldPath,ownerUid:A,now:()=>clock});
  const profile=(id,role,points=0,active=true)=>({userId:id,memberId:"TEST-"+id,nickname:"RELEASE DUMMY "+id.slice(-2),phone:"0800000000",role,isActive:active,monthlyPoints:points,lifetimeHours:17.5,pointsMonth:"2026-10",testRunId:runId,unknownLegacy:{preserve:true},createdAt:new Timestamp(1700000000,123456789)});
  for(const [id,role] of [[A,"admin"],[S,"staff"]]){await db.collection("users").doc(id).create(profile(id,role));await db.collection("memberStaffAccess").doc(id).create({role,enabled:true});}
  for(let i=0;i<ids.length;i++)await db.collection("users").doc(ids[i]).create(profile(ids[i],"member",[30,25,25,15,999,9][i],i!==4));
  await db.collection("posAwardMonths").doc("2026-10").create({state:"open"});
  await db.collection("posAwardMonths").doc("2026-11").create({state:"open"});
  assert.deepEqual((await service.session(S)).capabilities,{staff:true,admin:false});
  await db.collection("memberStaffAccess").doc(S).update({enabled:false});
  assert.deepEqual((await service.session(S)).capabilities,{staff:false,admin:false});
  await assert.rejects(service.addPoints(S,{userId:ids[3],monthId:"2026-10",points:1,requestId:runId}),{code:"permission-denied"});
  await db.collection("memberStaffAccess").doc(S).update({enabled:true});
  checks.push("live_server_capabilities_and_revocation");
  const d={userId:ids[5],monthId:"2026-10",points:1,requestId:runId};
  await Promise.all([service.addPoints(S,d),service.addPoints(S,d)]);
  clock=new Date("2026-11-01T00:00:00Z");
  assert.equal((await service.addPoints(S,d)).duplicate,true);
  await assert.rejects(service.addPoints(S,{...d,requestId:"aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"}),{code:"failed-precondition"});
  assert.equal((await db.collection("users").doc(ids[5]).get()).data().monthlyPoints,10);
  checks.push("manual_lost_ack_recovered_across_month_boundary");
  // Simulate a process dying after one immutable snapshot/reset committed.
  await db.collection("posAwardMonths").doc("2026-10").update({state:"closing"});
  const first=(await db.collection("users").doc(ids[0]).get()).data();
  await db.collection("seasonResults").doc("2026-10").collection("members").doc(ids[0]).create({userId:ids[0],nickname:first.nickname,memberId:first.memberId,points:30,eligible:true});
  await db.collection("users").doc(ids[0]).update({monthlyPoints:4,pointsMonth:"2026-11"});
  await assert.rejects(service.closeMonth(S,"2026-10"),{code:"permission-denied"});
  const result=await service.closeMonth(A,"2026-10");
  assert.deepEqual(result.top3.map(x=>[x.userId,x.points]),[[ids[0],30],[ids[1],25],[ids[2],25]]);
  assert.equal((await service.closeMonth(A,"2026-10")).duplicate,true);
  assert.equal((await db.collection("users").doc(ids[0]).get()).data().monthlyPoints,4);
  assert.equal((await db.collection("users").doc(ids[0]).get()).data().lifetimeHours,17.5);
  const rewards=await db.collection("monthlyRewards").get();assert.equal(rewards.size,4);
  assert.equal(rewards.docs.filter(x=>x.data().benefit==="limited_shirt").length,3);
  assert.equal(rewards.docs.filter(x=>x.data().type==="discount10").length,1);
  assert.ok(!rewards.docs.some(x=>x.data().userId===ids[4]));
  checks.push("top3_ties_inactive_exclusion_partial_close_resume_new_month_preserved");
  const shirt=rewards.docs.find(x=>x.data().type==="top1").id,discount=rewards.docs.find(x=>x.data().type==="discount10").id;
  await assert.rejects(service.redeem(ids[0],{rewardId:shirt}),{code:"permission-denied"});
  const shirts=await Promise.all([service.redeem(S,{rewardId:shirt}),service.redeem(S,{rewardId:shirt})]);
  assert.equal(shirts.filter(x=>!x.duplicate).length,1);
  await assert.rejects(service.redeem(S,{rewardId:discount}),{code:"invalid-argument"});
  const discounts=await Promise.all([service.redeem(S,{rewardId:discount,billRef:"TEST-RELEASE-BILL"}),service.redeem(S,{rewardId:discount,billRef:"test-release-bill"})]);
  assert.equal(discounts.filter(x=>!x.duplicate).length,1);
  await assert.rejects(service.redeem(S,{rewardId:discount,billRef:"TEST-OTHER-BILL"}),{code:"already-exists"});
  const second="2026-10_"+ids[5]+"_discount10";
  await db.collection("monthlyRewards").doc(second).create({userId:ids[5],monthKey:"2026-10",type:"discount10",status:"available"});
  await assert.rejects(service.redeem(S,{rewardId:second,billRef:"TEST-RELEASE-BILL"}),{code:"already-exists"});
  clock=new Date("2026-12-01T00:00:00Z");
  await assert.rejects(service.redeem(S,{rewardId:second,billRef:"TEST-FRESH-BILL"}),{code:"failed-precondition"});
  assert.equal((await db.collection("rewardRedemptions").get()).size,2);
  checks.push("shirt_discount_concurrent_once_bill_lock_expiry_and_audit");
  const collections=["users","memberStaffAccess","posAwardMonths","pointTransactions","seasonResults","monthlyRewards","publicLeaderboard","rewardRedemptions","rewardBillClaims"];
  const backup=await safety.exportData({root,sourceProject:physicalDb.projectId,collections,frozen:true});
  const key=randomBytes(32),encrypted=safety.seal(backup,key),restored=safety.unseal(encrypted,key);
  const corrupt=JSON.parse(encrypted);corrupt.tag=Buffer.alloc(16).toString("base64");assert.throws(()=>safety.unseal(JSON.stringify(corrupt),key));
  const targetPrefix="restoreRehearsals/"+runId,config={backup:restored,db:physicalDb,targetProject:physicalDb.projectId,targetPrefix,Timestamp,GeoPoint};
  assert.equal((await safety.restoreCreateOnly(config)).count,backup.count);
  await safety.restoreCreateOnly({...config,dryRun:false});
  const copy=await safety.exportData({root:physicalDb.doc(targetPrefix),sourceProject:physicalDb.projectId,collections,frozen:true});
  assert.equal(copy.recordsSha256,backup.recordsSha256);assert.equal(copy.count,backup.count);
  await assert.rejects(safety.restoreCreateOnly({...config,dryRun:false}));
  checks.push("encrypted_firestore_backup_restore_exact_hash_and_collision_block");
  return {checks,backupDocuments:backup.count,backupSha256:backup.recordsSha256,restoreSha256:copy.recordsSha256,productionWrites:0};
}
module.exports={releaseScenarios};
